def area_of_rectangle(length, breadth):
    """
    Calculate the area of a rectangle.

    Args:
        length (float or int): The length of the rectangle.
        breadth (float or int): The breadth (width) of the rectangle.

    Returns:
        float: The area of the rectangle (length * breadth).

    Example:
        >>> area_of_rectangle(10, 20)
        200
    """
    return length * breadth

# Example usage:
# To find the area of a rectangle with length 10 and breadth 20:
print("Area of rectangle (10 x 20):", area_of_rectangle(10, 20))

